"""Deterministic offline providers.

These make the whole application runnable and testable with **no API key and
no network**: the test suite uses them, and the hosted demo can fall back to
them if a key expires mid-review.

Everything here is **synthetic**. The weather is generated by a smooth
deterministic function of position and hour -- it is not a forecast, has never
been a forecast, and must never be presented to a user as current conditions.
Any surface showing fixture data is responsible for labelling it as a demo.

Determinism is the point: no randomness, no clock reads, no I/O. The same
inputs always produce byte-identical outputs, so tests that depend on these
providers cannot flake.
"""

from __future__ import annotations

import math
from collections.abc import Sequence
from datetime import UTC, datetime, timedelta
from typing import Final

from apps.routing.domain.geo import haversine_miles
from apps.routing.domain.models import Coordinate, RouteCandidate, WeatherSample

from .base import GeocodeResult, HourlyForecast, PlaceSuggestion, RouteSet
from .errors import GeocodingNoResultsError

__all__ = [
    "FIXTURE_PLACES",
    "FixtureGeocodingProvider",
    "FixtureRoutingProvider",
    "FixtureWeatherProvider",
    "synthetic_sample",
]

PROVIDER_NAME: Final = "fixtures"

#: A small gazetteer. An unknown query raises rather than returning an
#: approximate coordinate -- a fixture provider that quietly invents places
#: would hide bugs the real provider would expose.
FIXTURE_PLACES: Final[dict[str, tuple[str, float, float]]] = {
    "denver": ("Denver, CO, USA", 39.7392, -104.9903),
    "chicago": ("Chicago, IL, USA", 41.8781, -87.6298),
    "salt lake city": ("Salt Lake City, UT, USA", 40.7608, -111.8910),
    "omaha": ("Omaha, NE, USA", 41.2565, -95.9345),
    "kansas city": ("Kansas City, MO, USA", 39.0997, -94.5786),
    "cheyenne": ("Cheyenne, WY, USA", 41.1400, -104.8202),
    "minneapolis": ("Minneapolis, MN, USA", 44.9778, -93.2650),
    "dallas": ("Dallas, TX, USA", 32.7767, -96.7970),
    "phoenix": ("Phoenix, AZ, USA", 33.4484, -112.0740),
    "seattle": ("Seattle, WA, USA", 47.6062, -122.3321),
    "fairbanks": ("Fairbanks, AK, USA", 64.8378, -147.7164),
    "buffalo": ("Buffalo, NY, USA", 42.8864, -78.8784),
}


class FixtureGeocodingProvider:
    """Resolves a handful of known place names, offline."""

    name = PROVIDER_NAME

    def geocode(self, query: str) -> GeocodeResult:
        key = query.strip().lower()
        for name, (label, latitude, longitude) in FIXTURE_PLACES.items():
            if key == name or key.startswith(name + ",") or name in key:
                return GeocodeResult(
                    coordinate=Coordinate(latitude=latitude, longitude=longitude),
                    label=label,
                    provider=PROVIDER_NAME,
                    confidence=1.0,
                )
        raise GeocodingNoResultsError(
            f"No fixture location matches {query.strip()!r}. Known fixtures: "
            + ", ".join(sorted(FIXTURE_PLACES)),
            provider=PROVIDER_NAME,
            query=query,
        )

    def suggest(self, query: str, *, limit: int = 6) -> tuple[PlaceSuggestion, ...]:
        """Gazetteer entries whose name or label contains the query."""
        key = query.strip().lower()
        if len(key) < 2:
            return ()
        matches = [
            PlaceSuggestion(
                label=label,
                coordinate=Coordinate(latitude=latitude, longitude=longitude),
                provider=PROVIDER_NAME,
            )
            for name, (label, latitude, longitude) in FIXTURE_PLACES.items()
            if key in name or key in label.lower()
        ]
        return tuple(matches[: max(1, limit)])


class FixtureRoutingProvider:
    """Generates distinct synthetic route alternatives between two points.

    Three shapes are produced: a direct line, and two alternatives bowed
    perpendicular to it in opposite directions, with different lengths and
    average speeds. The bows are large enough that the real de-duplication
    rules treat them as genuinely different routes.
    """

    name = PROVIDER_NAME

    #: (label, lateral bow in degrees, distance multiplier, average mph)
    PROFILES: Final[tuple[tuple[str, float, float, float], ...]] = (
        ("Direct route", 0.0, 1.00, 55.0),
        ("Northern alternative", 0.9, 1.08, 58.0),
        ("Southern alternative", -0.7, 1.05, 50.0),
    )

    def __init__(self, *, vertices: int = 61, available: int = 3) -> None:
        if vertices < 2:
            raise ValueError("vertices must be at least 2")
        if not 1 <= available <= len(self.PROFILES):
            raise ValueError(f"available must be 1..{len(self.PROFILES)}")
        self.vertices = vertices
        #: Lets a test or demo simulate a provider that found fewer than three
        #: distinct routes, without pretending otherwise.
        self.available = available

    def routes(
        self,
        origin: Coordinate,
        destination: Coordinate,
        departure_time: datetime,
        *,
        max_alternatives: int = 2,
    ) -> RouteSet:
        if departure_time.tzinfo is None:
            raise ValueError("departure_time must be timezone-aware")

        wanted = min(self.available, max(0, max_alternatives) + 1)
        candidates = [
            self._build(origin, destination, index, *self.PROFILES[index])
            for index in range(wanted)
        ]

        notices: list[str] = [
            "Synthetic routes from the offline fixture provider; not real road geometry."
        ]
        requested_total = max(0, max_alternatives) + 1
        if len(candidates) < requested_total:
            notices.append(
                f"Fixture provider offers {len(candidates)} of the "
                f"{requested_total} routes requested."
            )

        return RouteSet(
            routes=tuple(candidates),
            provider=PROVIDER_NAME,
            requested_alternatives=max(0, max_alternatives),
            returned_count=len(candidates),
            duplicates_removed=0,
            notices=tuple(notices),
        )

    def _build(
        self,
        origin: Coordinate,
        destination: Coordinate,
        index: int,
        label: str,
        bow_degrees: float,
        distance_factor: float,
        average_mph: float,
    ) -> RouteCandidate:
        geometry = self._bowed_line(origin, destination, bow_degrees)
        straight = sum(
            haversine_miles(a, b) for a, b in zip(geometry, geometry[1:])
        )
        distance = max(1.0, straight * distance_factor)
        return RouteCandidate(
            id=f"{PROVIDER_NAME}-{index}",
            label=label,
            geometry=geometry,
            distance_miles=distance,
            duration_seconds=distance / average_mph * 3600.0,
            provider_index=index,
            segment_durations=None,
        )

    def _bowed_line(
        self, origin: Coordinate, destination: Coordinate, bow_degrees: float
    ) -> tuple[Coordinate, ...]:
        """A line from origin to destination, bowed sideways by a half-sine."""
        span_lat = destination.latitude - origin.latitude
        span_lon = destination.longitude - origin.longitude
        length = math.hypot(span_lat, span_lon) or 1.0
        # Unit normal to the origin->destination direction.
        normal_lat, normal_lon = -span_lon / length, span_lat / length

        points: list[Coordinate] = []
        for step in range(self.vertices):
            t = step / (self.vertices - 1)
            bow = math.sin(math.pi * t) * bow_degrees
            points.append(
                Coordinate(
                    latitude=_clamp(
                        origin.latitude + span_lat * t + normal_lat * bow, 90.0
                    ),
                    longitude=_clamp(
                        origin.longitude + span_lon * t + normal_lon * bow, 180.0
                    ),
                )
            )
        return tuple(points)


def synthetic_sample(coordinate: Coordinate, moment: datetime) -> WeatherSample:
    """A deterministic, plausible-looking synthetic observation.

    Smooth trigonometric functions of position and hour. Not a forecast.

    The shape is chosen so a long route passes through a range of conditions
    -- including occasional Severe and No Travel -- which is what makes the
    offline demo exercise the risk engine rather than showing 500 miles of
    uniform calm.
    """
    hours = moment.timestamp() / 3600.0
    lat, lon = coordinate.latitude, coordinate.longitude

    wind_wave = (
        math.sin(lat * 0.45) + math.cos(lon * 0.32) + math.sin(hours * 0.26)
    ) / 3.0
    wind = 14.0 + 30.0 * abs(wind_wave)

    rain_wave = math.sin(lat * 0.7 + hours * 0.18) * math.cos(lon * 0.21)
    rain = max(0.0, rain_wave) ** 3 * 0.9

    # Snow only where it is plausibly cold: high latitude, scaled in.
    cold = max(0.0, (lat - 38.0) / 12.0)
    snow_wave = math.sin(lon * 0.4 - hours * 0.14)
    snow = max(0.0, snow_wave) ** 2 * cold * 2.4

    return WeatherSample(
        wind_mph=round(wind, 2),
        rain_in_hr=round(rain, 4),
        snow_in_hr=round(snow, 4),
        wind_gust_mph=round(wind * 1.45, 2),
        forecast_time=moment,
    )


class FixtureWeatherProvider:
    """Synthesises hourly forecasts offline, deterministically."""

    name = PROVIDER_NAME

    def __init__(self, *, missing_every: int | None = None) -> None:
        #: When set, every Nth hour is returned with no measurements, so the
        #: UNKNOWN/coverage paths can be exercised without a provider outage.
        self.missing_every = missing_every

    def hourly(
        self,
        coordinates: Sequence[Coordinate],
        start: datetime,
        end: datetime,
    ) -> tuple[HourlyForecast, ...]:
        if start.tzinfo is None or end.tzinfo is None:
            raise ValueError("start and end must be timezone-aware")
        if end < start:
            raise ValueError("end must not precede start")

        first = start.astimezone(UTC).replace(minute=0, second=0, microsecond=0)
        hours = int((end.astimezone(UTC) - first).total_seconds() // 3600) + 1
        times = tuple(first + timedelta(hours=offset) for offset in range(hours))

        return tuple(
            HourlyForecast(
                coordinate=coordinate,
                resolved_coordinate=coordinate,
                times=times,
                samples=tuple(
                    self._sample(coordinate, moment, index)
                    for index, moment in enumerate(times)
                ),
                provider=PROVIDER_NAME,
            )
            for coordinate in coordinates
        )

    def _sample(
        self, coordinate: Coordinate, moment: datetime, index: int
    ) -> WeatherSample:
        if self.missing_every and index % self.missing_every == 0:
            return WeatherSample(
                wind_mph=None,
                rain_in_hr=None,
                snow_in_hr=None,
                forecast_time=moment,
            )
        return synthetic_sample(coordinate, moment)


def _clamp(value: float, limit: float) -> float:
    return max(-limit, min(limit, value))
